-- Additive migration: membership discount remains its own immutable snapshot.
CREATE TABLE loyalty_vouchers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(6) NOT NULL UNIQUE,
    customer_id BIGINT NOT NULL REFERENCES customer_profiles(user_id),
    points_cost INTEGER NOT NULL,
    discount_amount NUMERIC(15,2) NOT NULL,
    idempotency_key VARCHAR(100) NOT NULL,
    booking_id BIGINT UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    used_at TIMESTAMPTZ,
    CONSTRAINT uq_loyalty_vouchers_redemption UNIQUE(customer_id,idempotency_key),
    CONSTRAINT ck_loyalty_vouchers_code CHECK (code ~ '^[A-Z0-9]{6}$' AND code ~ '[A-Z]' AND code ~ '[0-9]'),
    CONSTRAINT ck_loyalty_vouchers_offer CHECK (
        (points_cost=50 AND discount_amount=400000) OR
        (points_cost=100 AND discount_amount=1000000) OR
        (points_cost=200 AND discount_amount=2200000)
    ),
    CONSTRAINT ck_loyalty_vouchers_used CHECK (used_at IS NULL OR booking_id IS NOT NULL),
    CONSTRAINT fk_loyalty_vouchers_booking_owner FOREIGN KEY(booking_id,customer_id)
        REFERENCES bookings(id,customer_id)
);
CREATE INDEX ix_loyalty_vouchers_customer ON loyalty_vouchers(customer_id,created_at DESC,id DESC);

ALTER TABLE bookings ADD COLUMN voucher_code VARCHAR(6) REFERENCES loyalty_vouchers(code);
ALTER TABLE bookings ADD COLUMN voucher_discount_amount NUMERIC(15,2) NOT NULL DEFAULT 0;
ALTER TABLE bookings DROP CONSTRAINT ck_bookings_amounts;
ALTER TABLE bookings ADD CONSTRAINT ck_bookings_amounts CHECK (
    base_amount>=0 AND discount_rate>=0 AND discount_rate<1
    AND discount_amount>=0 AND discount_amount<=base_amount
    AND voucher_discount_amount>=0 AND voucher_discount_amount<=base_amount-discount_amount
    AND payable_amount=base_amount-discount_amount-voucher_discount_amount
);
ALTER TABLE bookings ADD CONSTRAINT ck_bookings_voucher_pair CHECK (
    voucher_code IS NOT NULL OR voucher_discount_amount=0
);
