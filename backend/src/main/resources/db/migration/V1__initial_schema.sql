-- Canonical PostgreSQL schema for Hotel PMS Mini. All timestamps are instants
-- (TIMESTAMPTZ); API/local display must convert to the hotel timezone.
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(150) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_app_users_email_nonblank CHECK (btrim(email) <> ''),
    CONSTRAINT ck_app_users_full_name_nonblank CHECK (btrim(full_name) <> '')
);
CREATE UNIQUE INDEX uq_app_users_email_lower ON app_users (lower(email));

CREATE TABLE roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(30) NOT NULL UNIQUE,
    description VARCHAR(150) NOT NULL,
    CONSTRAINT ck_roles_code CHECK (code IN ('CUSTOMER', 'STAFF', 'ADMIN'))
);
INSERT INTO roles (code, description) VALUES
    ('CUSTOMER', 'Registered hotel customer'),
    ('STAFF', 'Hotel staff'),
    ('ADMIN', 'System administrator');

CREATE TABLE user_roles (
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    role_id BIGINT NOT NULL REFERENCES roles(id),
    PRIMARY KEY (user_id, role_id)
);
CREATE INDEX ix_user_roles_role_id ON user_roles (role_id);

CREATE TABLE customer_profiles (
    user_id BIGINT PRIMARY KEY REFERENCES app_users(id),
    phone_number VARCHAR(30),
    eligible_spend_total NUMERIC(15, 2) NOT NULL DEFAULT 0,
    points_balance BIGINT NOT NULL DEFAULT 0,
    tier_code VARCHAR(20) NOT NULL DEFAULT 'STANDARD',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_customer_profiles_spend_nonnegative CHECK (eligible_spend_total >= 0),
    CONSTRAINT ck_customer_profiles_points_nonnegative CHECK (points_balance >= 0),
    CONSTRAINT ck_customer_profiles_tier CHECK (tier_code IN ('STANDARD', 'VIP', 'DIAMOND'))
);
CREATE INDEX ix_customer_profiles_phone_number ON customer_profiles (phone_number);

CREATE TABLE room_types (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(30) NOT NULL UNIQUE,
    name VARCHAR(120) NOT NULL,
    description TEXT,
    max_occupancy SMALLINT NOT NULL,
    base_price_per_night NUMERIC(15, 2) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_room_types_code_nonblank CHECK (btrim(code) <> ''),
    CONSTRAINT ck_room_types_name_nonblank CHECK (btrim(name) <> ''),
    CONSTRAINT ck_room_types_occupancy_positive CHECK (max_occupancy > 0),
    CONSTRAINT ck_room_types_price_nonnegative CHECK (base_price_per_night >= 0)
);

CREATE TABLE physical_rooms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_type_id BIGINT NOT NULL REFERENCES room_types(id),
    room_number VARCHAR(30) NOT NULL UNIQUE,
    floor_number SMALLINT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_physical_rooms_id_type UNIQUE (id, room_type_id),
    CONSTRAINT ck_physical_rooms_number_nonblank CHECK (btrim(room_number) <> '')
);
CREATE INDEX ix_physical_rooms_room_type_id ON physical_rooms (room_type_id);

CREATE TABLE room_blocks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    physical_room_id BIGINT NOT NULL REFERENCES physical_rooms(id),
    start_at TIMESTAMPTZ NOT NULL,
    end_at TIMESTAMPTZ NOT NULL,
    reason TEXT NOT NULL,
    created_by_user_id BIGINT NOT NULL REFERENCES app_users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    released_by_user_id BIGINT REFERENCES app_users(id),
    released_at TIMESTAMPTZ,
    CONSTRAINT ck_room_blocks_period CHECK (start_at < end_at),
    CONSTRAINT ck_room_blocks_reason_nonblank CHECK (btrim(reason) <> ''),
    CONSTRAINT ck_room_blocks_release_pair CHECK ((released_at IS NULL) = (released_by_user_id IS NULL)),
    CONSTRAINT ex_room_blocks_active_overlap EXCLUDE USING gist (
        physical_room_id WITH =,
        tstzrange(start_at, end_at, '[)') WITH &&
    ) WHERE (released_at IS NULL)
);
CREATE INDEX ix_room_blocks_created_by_user_id ON room_blocks (created_by_user_id);
CREATE INDEX ix_room_blocks_released_by_user_id ON room_blocks (released_by_user_id);

CREATE TABLE bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_code VARCHAR(30) NOT NULL UNIQUE,
    customer_id BIGINT NOT NULL REFERENCES customer_profiles(user_id),
    room_type_id BIGINT NOT NULL REFERENCES room_types(id),
    physical_room_id BIGINT NOT NULL,
    guest_count SMALLINT NOT NULL,
    start_at TIMESTAMPTZ NOT NULL,
    end_at TIMESTAMPTZ NOT NULL,
    hold_expires_at TIMESTAMPTZ NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING_PAYMENT',
    base_amount NUMERIC(15, 2) NOT NULL,
    discount_rate NUMERIC(5, 4) NOT NULL DEFAULT 0,
    discount_amount NUMERIC(15, 2) NOT NULL DEFAULT 0,
    payable_amount NUMERIC(15, 2) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    confirmed_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    cancelled_at TIMESTAMPTZ,
    expired_at TIMESTAMPTZ,
    CONSTRAINT fk_bookings_physical_room_type FOREIGN KEY (physical_room_id, room_type_id)
        REFERENCES physical_rooms(id, room_type_id),
    CONSTRAINT uq_bookings_id_customer UNIQUE (id, customer_id),
    CONSTRAINT ck_bookings_code_nonblank CHECK (btrim(booking_code) <> ''),
    CONSTRAINT ck_bookings_guests_positive CHECK (guest_count > 0),
    CONSTRAINT ck_bookings_period CHECK (start_at < end_at),
    CONSTRAINT ck_bookings_status CHECK (status IN (
        'PENDING_PAYMENT', 'CONFIRMED', 'COMPLETED', 'CANCELLED', 'EXPIRED'
    )),
    CONSTRAINT ck_bookings_amounts CHECK (
        base_amount >= 0 AND discount_rate >= 0 AND discount_rate < 1
        AND discount_amount >= 0 AND discount_amount <= base_amount
        AND payable_amount = base_amount - discount_amount
    ),
    CONSTRAINT ex_bookings_room_overlap EXCLUDE USING gist (
        physical_room_id WITH =,
        tstzrange(start_at, end_at, '[)') WITH &&
    ) WHERE (status IN ('PENDING_PAYMENT', 'CONFIRMED', 'COMPLETED'))
);
CREATE INDEX ix_bookings_customer_id_created_at ON bookings (customer_id, created_at DESC);
CREATE INDEX ix_bookings_room_type_id ON bookings (room_type_id);
CREATE INDEX ix_bookings_status_hold_expires_at ON bookings (status, hold_expires_at);
CREATE INDEX ix_bookings_status_end_at ON bookings (status, end_at);

CREATE TABLE payment_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL REFERENCES bookings(id),
    provider VARCHAR(20) NOT NULL,
    idempotency_key VARCHAR(100) NOT NULL,
    provider_transaction_id VARCHAR(100),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    requested_amount NUMERIC(15, 2) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    succeeded_at TIMESTAMPTZ,
    CONSTRAINT uq_payment_attempts_idempotency UNIQUE (booking_id, provider, idempotency_key),
    CONSTRAINT ck_payment_attempts_provider CHECK (provider IN ('DEMO', 'VNPAY')),
    CONSTRAINT ck_payment_attempts_status CHECK (status IN ('PENDING', 'SUCCEEDED', 'FAILED')),
    CONSTRAINT ck_payment_attempts_amount_nonnegative CHECK (requested_amount >= 0)
);
CREATE INDEX ix_payment_attempts_booking_id ON payment_attempts (booking_id);
CREATE UNIQUE INDEX uq_payment_attempts_provider_transaction
    ON payment_attempts (provider, provider_transaction_id)
    WHERE provider_transaction_id IS NOT NULL;
CREATE UNIQUE INDEX uq_payment_attempts_one_success_per_booking
    ON payment_attempts (booking_id) WHERE status = 'SUCCEEDED';

CREATE TABLE loyalty_awards (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL UNIQUE,
    customer_id BIGINT NOT NULL,
    eligible_amount NUMERIC(15, 2) NOT NULL,
    points_awarded BIGINT NOT NULL,
    awarded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_loyalty_awards_booking_customer FOREIGN KEY (booking_id, customer_id)
        REFERENCES bookings(id, customer_id),
    CONSTRAINT ck_loyalty_awards_amount_nonnegative CHECK (eligible_amount >= 0),
    CONSTRAINT ck_loyalty_awards_points_nonnegative CHECK (points_awarded >= 0)
);
CREATE INDEX ix_loyalty_awards_customer_id ON loyalty_awards (customer_id);
