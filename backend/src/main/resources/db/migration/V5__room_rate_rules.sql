CREATE TABLE room_rate_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_type_id BIGINT NOT NULL REFERENCES room_types(id),
    kind VARCHAR(16) NOT NULL CHECK (kind IN ('OVERRIDE', 'HOLIDAY', 'SEASONAL', 'WEEKEND')),
    starts_on DATE NOT NULL,
    ends_on DATE NOT NULL,
    nightly_rate NUMERIC(15,2) NOT NULL CHECK (nightly_rate >= 0),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CHECK (ends_on - starts_on BETWEEN 0 AND 365),
    CONSTRAINT ex_room_rate_rule_overlap EXCLUDE USING gist (
        room_type_id WITH =, kind WITH =, daterange(starts_on, ends_on, '[]') WITH &&
    ) WHERE (is_active)
);

