-- Database uniqueness is the final guard for concurrent create/update requests.
CREATE UNIQUE INDEX uq_physical_rooms_number_normalized
    ON physical_rooms (lower(btrim(room_number)));

CREATE TABLE room_type_images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_type_id BIGINT NOT NULL REFERENCES room_types(id) ON DELETE CASCADE,
    sort_order SMALLINT NOT NULL CHECK (sort_order BETWEEN 0 AND 4),
    is_cover BOOLEAN NOT NULL DEFAULT FALSE,
    content_type VARCHAR(20) NOT NULL CHECK (content_type IN ('image/jpeg', 'image/png')),
    image_data BYTEA NOT NULL CHECK (octet_length(image_data) BETWEEN 1 AND 5242880),
    width INTEGER NOT NULL CHECK (width BETWEEN 1 AND 6000),
    height INTEGER NOT NULL CHECK (height BETWEEN 1 AND 6000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_room_type_image_position UNIQUE (room_type_id, sort_order)
);
CREATE UNIQUE INDEX uq_room_type_image_cover ON room_type_images(room_type_id) WHERE is_cover;
