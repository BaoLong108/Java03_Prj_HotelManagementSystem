CREATE TABLE check_in_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL REFERENCES bookings(id),
    estimated_arrival_at TIMESTAMPTZ NOT NULL,
    early_check_in_requested BOOLEAN NOT NULL,
    arrival_note VARCHAR(500),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    reviewed_by BIGINT REFERENCES app_users(id),
    reviewed_at TIMESTAMPTZ,
    rejection_reason VARCHAR(300),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_check_in_request_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED')),
    CONSTRAINT ck_check_in_request_review CHECK (
        (status IN ('APPROVED', 'REJECTED') AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL)
        OR (status IN ('PENDING', 'CANCELLED') AND reviewed_by IS NULL AND reviewed_at IS NULL)
    ),
    CONSTRAINT ck_check_in_request_rejection CHECK (
        (status = 'REJECTED' AND rejection_reason IS NOT NULL AND btrim(rejection_reason) <> '')
        OR (status <> 'REJECTED' AND rejection_reason IS NULL)
    )
);

CREATE UNIQUE INDEX uq_check_in_requests_active_booking
    ON check_in_requests(booking_id) WHERE status IN ('PENDING', 'APPROVED');
CREATE INDEX ix_check_in_requests_booking_history ON check_in_requests(booking_id, id DESC);
CREATE INDEX ix_check_in_requests_queue ON check_in_requests(status, id DESC);
